/* modlink-agent — слой платформы для lwIP.
 *
 * В режиме NO_SYS от порта требуется ровно одна вещь — часы. Ни мьютексов, ни
 * семафоров, ни почтовых ящиков: стек живёт в одном потоке. */
#include "lwip/opt.h"
#include "lwip/sys.h"

#define WIN32_LEAN_AND_MEAN
#include <windows.h>

/* Монотонные миллисекунды. lwIP сравнивает эти значения только вычитанием, и
 * переполнение u32 (через ~49 суток непрерывной работы) обрабатывается им
 * корректно именно за счёт беззнаковой арифметики — поэтому просто усекаем,
 * а не пытаемся хитрить с базой отсчёта. */
u32_t sys_now(void)
{
    return (u32_t)GetTickCount64();
}
